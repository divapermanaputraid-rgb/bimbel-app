// seed-bank-soal-mtk.js — reads JSON, generates SQL migration
const fs = require('fs');
const path = require('path');

function escapeSql(str) {
  if (str === null || str === undefined) return 'NULL';
  return "'" + String(str).replace(/'/g, "''") + "'";
}
function escapeJson(obj) {
  if (obj === null || obj === undefined) return 'NULL';
  return "'" + JSON.stringify(obj).replace(/'/g, "''") + "'::jsonb";
}

const files = [
  'data/bank-soal-mtk-k1.json',
  'data/bank-soal-mtk-k2.json',
  'data/bank-soal-mtk-k3.json',
  'data/bank-soal-mtk-k6.json',
];

const rows = [];

for (const file of files) {
  const data = JSON.parse(fs.readFileSync(path.join(__dirname, '..', file), 'utf8'));
  const subjectId = `k${data.kelas}-mtk`;
  for (const unit of data.units) {
    for (const soal of unit.soal) {
      const tipe = soal.tipe === 'truefalse' ? 'true_false'
        : soal.tipe === 'fill' ? 'fill_blank'
        : soal.tipe === 'match' ? 'match'
        : 'choose_correct';
      const pilihan = soal.pilihan ?? (soal.pasangan ? Object.keys(soal.pasangan) : ['Benar', 'Salah']);
      const jawabanBenar = soal.tipe === 'truefalse' ? (soal.jawaban === true ? 'Benar' : 'Salah')
        : soal.tipe === 'match' ? soal.jawaban
        : soal.jawaban;
      rows.push(`(
  ${escapeSql(soal.id)},
  ${escapeSql(unit.unit_id)},
  ${escapeSql(subjectId)},
  ${data.kelas},
  ${escapeSql(tipe)},
  ${escapeSql(soal.pertanyaan)},
  ${escapeJson(pilihan)},
  ${escapeJson(jawabanBenar)},
  1,
  10
)`);
    }
  }
}

const sql = `-- seed-bank-soal-mtk.sql — generated by seed-bank-soal-mtk.js
-- 316 soal MTK: K1(54) + K2(100) + K3(72) + K6(90)

DELETE FROM public.questions WHERE material_id LIKE 'k1-mtk-%' OR material_id LIKE 'k2-mtk-%' OR material_id LIKE 'k3-mtk-%' OR material_id LIKE 'k6-mtk-%';

INSERT INTO public.questions (
  id, material_id, subject_id, kelas, tipe, soal, pilihan, jawaban_benar, level, xp
) VALUES
${rows.join(',\n')};
`;

const outPath = path.join(__dirname, '../supabase/migrations/035_seed_bank_soal_mtk.sql');
fs.writeFileSync(outPath, sql, 'utf8');
console.log(`Written: ${outPath} (${rows.length} rows)`);
