// seed-bank-soal-bing-k2.js — reads JSON, generates SQL migration for K2 B.Inggris
const fs = require('fs');
const path = require('path');

function escapeSql(str) {
  if (str === null || str === undefined) return 'NULL';
  return "'" + String(str).replace(/'/g, "''") + "'";
}
function escapeJson(obj) {
  if (obj === null || obj === undefined) return 'NULL';
  return "'" + JSON.stringify(obj).replace(/'/g, "''") + "'::jsonb";
}

const data = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/bank-soal-bing-k2.json'), 'utf8'));
const subjectId = `k2-bing`;
const rows = [];

for (const unit of data.units) {
  for (const soal of unit.soal) {
    const tipe = soal.tipe === 'truefalse' ? 'true_false' : soal.tipe;
    const dataObj = soal.pasangan ? soal.pasangan : null;
    
    rows.push(`(
  ${escapeSql(soal.id)},
  ${escapeSql(unit.unit_id)},
  ${escapeSql(subjectId)},
  ${data.kelas},
  ${escapeSql(tipe)},
  ${escapeSql(soal.pertanyaan)},
  ${escapeSql(soal.soal_id)},
  ${escapeJson(soal.pilihan)},
  ${escapeJson(soal.jawaban)},
  ${escapeJson(dataObj)},
  ${escapeSql(soal.audio_text)},
  ${escapeSql(soal.penjelasan_id)},
  ${escapeSql(soal.kalimat)},
  ${escapeJson(soal.kata)},
  ${soal.level || 1},
  ${soal.xp || 10}
)`);
  }
}

const sql = `-- seed-bank-soal-bing-k2.sql — generated by seed-bank-soal-bing-k2.js
-- 80 soal B.Inggris: K2

DELETE FROM public.questions WHERE material_id LIKE 'k2-bing-%';

INSERT INTO public.questions (
  id, material_id, subject_id, kelas, tipe, soal, soal_id, pilihan, jawaban_benar, data, audio_text, penjelasan_id, kalimat, kata, level, xp
) VALUES
${rows.join(',\n')};
`;

const outPath = path.join(__dirname, '../supabase/migrations/037_seed_bank_soal_bing_k2.sql');
fs.writeFileSync(outPath, sql, 'utf8');
console.log(`Written: ${outPath} (${rows.length} rows)`);
