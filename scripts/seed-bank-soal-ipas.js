// seed-bank-soal-ipas.js — reads JSON, inserts into Supabase questions table
// Usage: node scripts/seed-bank-soal-ipas.js
// Requires: SUPABASE_URL, SUPABASE_SERVICE_KEY in env (or .env.local)
const fs = require('fs');
const path = require('path');

function escapeSql(str) {
  if (str === null || str === undefined) return 'NULL';
  if (typeof str === 'boolean') return str ? 'true' : 'false';
  return "'" + String(str).replace(/'/g, "''") + "'";
}
function escapeJson(obj) {
  if (obj === null || obj === undefined) return 'NULL';
  return "'" + JSON.stringify(obj).replace(/'/g, "''") + "'::jsonb";
}

const files = [
  'data/bank-soal-ipas-k3.json',
  'data/bank-soal-ipas-k4.json',
  'data/bank-soal-ipas-k5.json',
  'data/bank-soal-ipas-k6.json',
];

const rows = [];

for (const file of files) {
  const data = JSON.parse(fs.readFileSync(path.join(__dirname, '..', file), 'utf8'));
  const subjectId = `k${data.kelas}-ipas`;
  for (const unit of data.units) {
    for (const soal of unit.soal) {
      const tipe = soal.tipe === 'truefalse' ? 'true_false'
        : soal.tipe === 'fill' ? 'fill_blank'
        : soal.tipe === 'match' ? 'match'
        : 'choose_correct';
      const pilihan = soal.pilihan ?? (soal.pasangan ? Object.keys(soal.pasangan) : soal.tipe === 'truefalse' ? ['Benar', 'Salah'] : null);
      const jawabanBenar = soal.tipe === 'truefalse' ? (soal.jawaban === true ? 'Benar' : 'Salah')
        : soal.tipe === 'match' ? soal.jawaban
        : soal.jawaban;
      rows.push(`(
  ${escapeSql(soal.id)},
  ${escapeSql(unit.unit_id)},
  ${escapeSql(subjectId)},
  ${data.kelas},
  ${escapeSql(tipe)},
  ${escapeSql(soal.pertanyaan)},
  ${escapeJson(pilihan)},
  ${escapeJson(jawabanBenar)},
  NULL,
  1,
  10
)`);
    }
  }
}

let sql = `-- seed-bank-soal-ipas.sql — generated by seed-bank-soal-ipas.js
-- 129 soal IPAS: K3(32) + K4(32) + K5(25) + K6(40)

DELETE FROM public.questions WHERE material_id LIKE 'k3-ipas-%' OR material_id LIKE 'k4-ipas-%' OR material_id LIKE 'k5-ipas-%' OR material_id LIKE 'k6-ipas-%';

INSERT INTO public.questions (
  id, material_id, tipe, soal, pilihan, jawaban_benar, audio_text, level, xp
) VALUES
${rows.join(',\n')};
`;

const outPath = path.join(__dirname, '../supabase/migrations/034_seed_bank_soal_ipas.sql');
fs.writeFileSync(outPath, sql, 'utf8');
console.log(`Written: ${outPath} (${rows.length} rows)`);
